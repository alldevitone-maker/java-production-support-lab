"""Generate database seed from the shared fixture used by the browser demo."""
import json
from pathlib import Path
import sys
root=Path(__file__).resolve().parents[1]
rows=json.loads((root/'catalog/institutions.json').read_text())
quote=lambda s: "'"+str(s).replace("'","''")+"'"
lines=['-- Generated by scripts/generate-seed.py from catalog/institutions.json.']
for r in rows:
 lines.append('INSERT INTO institutions(id,name,kind,color,initials) VALUES('+','.join(quote(r[k]) for k in ['id','name','kind','color','initials'])+');')
 lines.append('INSERT INTO connectors(id,institution_id,profile,latency_ms,status) VALUES('+','.join([quote('connector-'+r['id']),quote(r['id']),quote(r['profile']),str(r['latencyMs']),"'READY'"])+');')
text='\n'.join(lines)+'\n'
p=root/'backend/src/main/resources/db/migration/V2__seed_institutions.sql'
if '--check' in sys.argv:
 assert p.read_text()==text,'SQL seed differs from catalog. Run python3 scripts/generate-seed.py.'
 print('SQL seed matches shared fixture.')
else:p.write_text(text)
